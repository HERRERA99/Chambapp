export function Icon({
  name,
  size = 18,
  className = '',
}: {
  name: IconName;
  size?: number;
  className?: string;
}) {
  const Component = icons[name];
  return (
    <Component size={size} strokeWidth={1.75} aria-hidden="true" className={`icon ${className}`} />
  );
}
